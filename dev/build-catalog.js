'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(__dirname, 'research', name), 'utf8'));
const sites = [...read('tier1.json'), ...read('tier2.json'), ...read('tier3.json'), ...read('tier4.json'), read('tier4-xuanmu.json'), read('joke.json')];
const ids = new Set();
for (const site of sites) {
  if (ids.has(site.id)) throw new Error('Duplicate campsite ID: ' + site.id);
  ids.add(site.id);
  for (const field of ['id', 'name', 'place', 'drive', 'price', 'slots', 'intro', 'season', 'q']) if (typeof site[field] !== 'string') throw new Error(site.id + ': missing ' + field);
  if (!site.joke && (!site.review || !site.reviewSource?.url || !site.sources)) throw new Error(site.id + ': missing research sources');
  for (const source of [...site.sources || [], site.reviewSource].filter(Boolean)) if (!/^https:\/\//.test(source.url)) throw new Error(site.id + ': invalid source URL');
  site.legal = site.legal || '';
  site.checkedAt = site.checkedAt || '2026-11-05';
  site.src = site.joke ? '主揪本人親自勘查' : '回饋與基本資料查核：' + site.checkedAt;
}
for (const tier of [1, 2, 3, 4]) {
  const count = sites.filter(s => s.tier === tier && !s.joke).length;
  if (count < 10) throw new Error('Tier ' + tier + ' has only ' + count + ' campsites');
  console.log('Tier ' + tier + ': ' + count + ' campsites');
}
fs.writeFileSync(path.join(root, 'camps.js'), '// Researched campsite catalog. Regenerate with node dev/build-catalog.js.\nwindow.CAMP_SITES = ' + JSON.stringify(sites, null, 2) + ';\n');
const catalog = sites.map(({id,name,place,intro}) => ({id,name,place,intro}));
fs.writeFileSync(path.join(root, 'apps-script', 'Catalog.gs'), '// Generated by node dev/build-catalog.js; retain IDs to preserve votes.\nconst CAMP_CATALOG = ' + JSON.stringify(catalog, null, 2) + ';\n');
console.log('Wrote public catalog and backend allowlist: ' + sites.length + ' entries');
